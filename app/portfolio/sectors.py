def sector_for(code: str) -> str:
    """Secteur d'une action ; `NON_CLASSE` si le code n'est pas (encore) répertorié ci-dessus."""
    return SECTORS.get(code, NON_CLASSE)


def all_sectors() -> list[str]:
    """Liste des secteurs réellement utilisés, triée alphabétiquement — pour peupler les filtres
    du tableau de bord sans jamais lister un secteur qu'aucune action n'utilise."""
    return sorted(set(SECTORS.values()))
